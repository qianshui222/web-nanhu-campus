const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const {chromium} = require('playwright')
const baseURL = process.env.NANHU_TEST_URL || 'http://127.0.0.1:8086'
const output = process.env.NANHU_ASSET_REPORT || path.join(__dirname,'../docs/assets/browser-verification.json')

async function check() {
  const browser = await chromium.launch({executablePath:process.env.NANHU_BROWSER,
      args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-crash-reporter']})
  try {
    const page = await browser.newPage({baseURL,viewport:{width:1440,height:900}})
    const errors = [], requestErrors = []
    page.on('pageerror',e=>errors.push(e.message))
    page.on('response',r=>{if(r.url().includes('/assets/') && !r.ok())requestErrors.push([r.status(),r.url()])})
    const started = Date.now()
    await page.goto('/')
    const map = page.locator('.map-view[data-glb-count="24"]')
    await map.waitFor({timeout:45000})
    const loadedMs = Date.now()-started
    const {revision,scene} = await (await page.request.get('/api/scene')).json()
    const buildings = scene.places.filter(p=>p.h>0)
    const ids = buildings.map(p=>p.id).sort()
    assert.deepEqual((await map.getAttribute('data-glb-ids')).split(',').sort(),ids)
    const resources = await page.evaluate(()=>performance.getEntriesByType('resource')
      .filter(e=>e.name.endsWith('.glb')||e.name.endsWith('draco_decoder.wasm'))
      .map(e=>({name:new URL(e.name).pathname,bytes:e.encodedBodySize,duration:Math.round(e.duration)})))
    assert.equal(resources.filter(r=>r.name.endsWith('.glb')).length,24)
    for (const p of buildings) assert(resources.some(r=>r.name===p.asset.model && r.bytes>1000))
    assert(resources.some(r=>r.name.endsWith('draco_decoder.wasm')))
    const canteen=scene.places.find(p=>p.id==='canteen')
    const entry=scene.nodes.find(n=>n.id===canteen.entry)
    const spur=scene.edges.find(e=>e.id==='canteen-door-spur')
    const a=canteen.angle*Math.PI/180
    const u= Math.cos(a)*(entry.x-canteen.x)-Math.sin(a)*(entry.z-canteen.z)
    const v= Math.sin(a)*(entry.x-canteen.x)+Math.cos(a)*(entry.z-canteen.z)
    assert(Math.abs(u-canteen.asset.doorOffset)<.002)
    assert(Math.abs(v-canteen.d/2-2.2)<.002)
    await page.getByRole('button',{name:'校园环境',exact:true}).click()
    const env=page.getByRole('dialog',{name:'校园环境'})
    await env.getByText(/现实同步/).waitFor()
    await env.getByLabel('启用测试预览').check()
    await env.getByLabel('测试时间（北京）').fill('2026-11-24T12:30')
    await env.getByLabel('测试天气').selectOption('clear')
    await page.getByRole('button',{name:'关闭环境'}).click()
    const search=page.getByRole('searchbox').or(page.getByPlaceholder(/搜索建筑/)).first()
    await search.fill('食堂')
    await page.locator('.place-row').filter({hasText:'南湖食堂'}).click()
    const heading=page.getByRole('heading',{name:'南湖食堂',exact:true})
    await heading.waitFor()
    await page.locator('.context').getByRole('button',{name:/关闭/}).click()
    const canvas=page.locator('.map-view canvas')
    const bounds=await canvas.boundingBox()
    await page.waitForTimeout(1020)
    await canvas.click({position:{x:bounds.width*.5,y:bounds.height*.50}})
    await heading.waitFor()
    await page.locator('.context').getByRole('button',{name:/关闭/}).click()
    await page.getByRole('button',{name:'第一人称',exact:true}).click()
    const dot=page.locator('.minimap svg circle[r="8"]').last()
    const cameraPosition=async()=>({x:+await dot.getAttribute('cx'),z:+await dot.getAttribute('cy')})
    await page.waitForTimeout(400)
    const spawn=await cameraPosition()
    const forecourt=scene.nodes.find(n=>n.id==='canteen-forecourt')
    assert(Math.hypot(spawn.x-forecourt.x,spawn.z-forecourt.z)<.2)
    await page.keyboard.down('w');await page.waitForTimeout(2200);await page.keyboard.up('w')
    await page.waitForTimeout(250)
    const walked=await cameraPosition()
    assert(Math.hypot(spawn.x-walked.x,spawn.z-walked.z)>4)
    const depth=Math.sin(a)*(walked.x-canteen.x)+Math.cos(a)*(walked.z-canteen.z)
    assert(depth>=canteen.d/2+.39)
    await page.getByRole('button',{name:'复位视角',exact:true}).click()
    await page.getByRole('button',{name:'路径规划',exact:true}).click()
    const fields=page.locator('.context select')
    await fields.first().selectOption('d5')
    await fields.last().selectOption('canteen')
    const pending=page.waitForResponse(r=>r.url().endsWith('/api/route/compare')&&r.request().method()==='POST')
    await page.getByRole('button',{name:'计算路线',exact:true}).click()
    const result=await (await pending).json()
    assert.equal(result.route.points.at(-1).id,entry.id)
    assert.equal(result.route.edges.at(-1),spur.id)
    assert.equal(result.astar.distance,result.dijkstra.distance)
    await page.getByRole('button',{name:'模拟导航',exact:true}).click()
    await page.getByRole('button',{name:'暂停',exact:true}).waitFor()
    assert.deepEqual(errors,[])
    assert.deepEqual(requestErrors,[])

    const other=await browser.newPage({baseURL,viewport:{width:1280,height:800}})
    await other.route('**/canteen.glb',r=>r.abort())
    await other.goto('/')
    await other.getByRole('alert').filter({hasText:'canteen'}).waitFor()
    await other.unroute('**/canteen.glb')
    await other.getByRole('button',{name:'重试楼体资源'}).click()
    await other.locator('.map-view[data-glb-count="24"]').waitFor({timeout:45000})
    assert.equal(await other.getByText('部分楼体加载失败').count(),0)
    fs.writeFileSync(output,JSON.stringify({revision,loadedMs,resources,buildingIds:ids,errors,requestErrors,
      canteen:{entry,forecourt,routeMeters:result.route.meters,spur:spur.id,spawn,collisionStop:walked},
      passed:['逐栋加载','静态资源请求','复用本地 Draco','搜索与模型子部件拾取','第一人称入口与碰撞','新入口导航','故障提示及重试']},null,2)+'\n')
    console.log('PASS',ids.length,'buildings; load',loadedMs,'ms; route to canteen',result.route.meters,'m')
  }finally{await browser.close()}
}
check().catch(e=>{console.error(e);process.exitCode=1})
