const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

async function main() {
  const [base='http://127.0.0.1:8080', out='docs/paper-ui/after'] = process.argv.slice(2)
  fs.mkdirSync(out,{recursive:true})
  const browser = await chromium.launch({
    executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',
    args: ['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader'],
  })
  const problems=[]
  const capture=(page,name)=>page.screenshot({path:path.join(out,name+'.png'),animations:'disabled'})
  const click=(page,name)=>page.getByRole('button',{name,exact:true}).click()
  try {
    for (const [name,width,height] of [['desktop',1440,900],['tablet',754,900],['phone',390,844]]) {
      const page=await browser.newPage({viewport:{width,height},deviceScaleFactor:name==='phone'?2:1,hasTouch:name==='phone'})
      page.on('pageerror',e=>problems.push(e.message))
      page.on('console',e=>{if(e.type()==='error')problems.push(e.text())})
      page.on('response',r=>{if(r.status()>=400)problems.push(r.status()+' '+r.url())})
      await page.goto(base+'/#/campus',{waitUntil:'networkidle'})
      await page.locator('[data-glb-count="24"]').waitFor({timeout:60000})
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),width)
      const canvas=page.locator('.three-host canvas')
      const initial=await canvas.boundingBox()
      assert.equal(initial.width,width)
      assert.equal(Math.round(initial.y+initial.height),height)
      assert.equal(await canvas.evaluate(c=>Math.round(c.width/c.getBoundingClientRect().width*100)/100)>0,true)
      assert.equal(await page.getByRole('button',{name:/^校园小地图/}).getAttribute('aria-expanded'),String(name!=='phone'))
      await capture(page,name)
      console.log(name+' / 24 GLB, canvas '+initial.width+'×'+initial.height)
      await click(page,'使用指南')
      const guide=page.getByRole('dialog',{name:'使用指南'})
      await guide.waitFor()
      assert.equal(await page.evaluate(()=>document.elementFromPoint(innerWidth*.54,innerHeight*.55)?.tagName), 'DIALOG')
      if(name==='phone') await capture(page,'phone-guide')
      for(let i=0;i<4;i++){
        await page.keyboard.press('Tab')
        assert(await page.evaluate(()=>document.activeElement===document.body || !!document.activeElement.closest('dialog[open]')))
      }
      await page.keyboard.press('Escape')
      await guide.waitFor({state:'hidden'})
      assert.equal(await page.evaluate(()=>document.activeElement.textContent.trim()),'使用指南')
      await click(page,'校园地点')
      const drawer=page.getByRole('dialog',{name:'校园地点'})
      const search=drawer.getByRole('searchbox')
      await search.fill('综合楼')
      await drawer.locator('.place-row').first().waitFor()
      if(name==='tablet') await capture(page,'tablet-places')
      await drawer.locator('.place-row').first().click()
      await drawer.waitFor({state:'hidden'})
      await page.locator('.context h2').getByText(/综合楼/).waitFor()
      if(name==='phone') await capture(page,'phone-detail')
      assert.deepEqual(await canvas.boundingBox(),initial)
      await click(page,'关闭侧栏')
      await click(page,'北向俯视')
      await click(page,'复位视角')
      await page.getByRole('combobox',{name:'画质'}).selectOption('detailed')
      await page.getByRole('combobox',{name:'画质'}).selectOption('balanced')
      if(name==='phone') {
        const minimap=page.getByRole('button',{name:/^校园小地图/})
        await minimap.click()
        assert.equal(await minimap.getAttribute('aria-expanded'),'true')
        await minimap.click()
      }
      await click(page,'开始漫游')
      await page.locator('.map-view.is-walking').waitFor()
      if(name==='desktop') await capture(page,'desktop-walk')
      await click(page,'退出漫游')
      await page.locator('.map-view.is-walking').waitFor({state:'hidden'})
      await click(page,'工具')
      const tools=page.getByRole('dialog',{name:'地图工具'})
      await tools.getByText('地图版本').waitFor()
      await tools.getByText('校园时间').waitFor()
      await tools.getByText('天气',{exact:true}).waitFor()
      if(name==='desktop'){
        await capture(page,'desktop-tools')
        await click(page,'渲染指标')
        await page.locator('.render-metrics').getByText(/FPS/).waitFor()
        console.log('metrics '+(await page.locator('.render-metrics').innerText()).replace(/\n/g,' / '))
        await click(page,'工具')
        await click(page,'渲染指标')
        await click(page,'校园地点')
        await click(page,'路径规划')
        await click(page,'计算路线')
        await page.locator('.route-strip').waitFor()
        console.log('route '+await page.locator('.route-strip strong').innerText())
        await capture(page,'desktop-route')
        const routeText=await page.locator('.route-strip strong').innerText()
        await click(page,'工具')
        await click(page,'路网检查')
        const inspector=page.getByRole('dialog',{name:/路网/})
        await inspector.waitFor()
        await inspector.getByRole('button',{name:/关闭/}).first().click()
        assert.equal(await page.locator('.route-strip strong').innerText(),routeText)
      } else {
        await page.keyboard.press('Escape')
      }
      await click(page,'菜单')
      await page.getByRole('dialog',{name:'导航菜单'}).getByRole('button',{name:'个人空间',exact:true}).click()
      await page.getByRole('dialog',{name:'登录账号'}).waitFor()
      await click(page,'注册新账号')
      await page.getByRole('heading',{name:'注册账号'}).waitFor()
      await page.keyboard.press('Escape')
      await page.getByRole('dialog',{name:'注册账号'}).waitFor({state:'hidden'})
      const emptyPoint={x:Math.round(width*.16),y:Math.round(height*.68)}
      assert.equal(await canvas.evaluate((c,p)=>document.elementFromPoint(p.x,p.y)===c,emptyPoint),true)
      const label=page.locator('.map-label[data-place="complex"]')
      const beforeDrag=await label.evaluate(el=>el.style.transform)
      await page.mouse.move(emptyPoint.x,emptyPoint.y)
      await page.mouse.down()
      await page.mouse.move(emptyPoint.x+30,emptyPoint.y+25,{steps:5})
      await page.mouse.up()
      await page.waitForFunction(before=>document.querySelector('.map-label[data-place="complex"]').style.transform!==before,beforeDrag)
      assert.deepEqual(await canvas.boundingBox(),initial)
      if (name==='desktop' && process.env.NANHU_TEST_SIGNUP==='1') {
        await click(page,'登录 / 注册')
        const account=page.getByRole('dialog')
        await account.getByLabel('账号',{exact:true}).fill('paper_'+Date.now().toString(36))
        await account.getByLabel('密码',{exact:true}).fill('Paper-view-verify21!')
        await click(page,'注册并登录')
        await account.waitFor({state:'hidden'})
        await click(page,'校园地点')
        await page.locator('.place-row').first().click()
        await click(page,'收藏地点')
        await page.getByRole('button',{name:'取消收藏',exact:true}).waitFor()
        await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:'个人空间'}).click()
        await page.getByRole('heading',{name:'我的南湖'}).waitFor()
        await click(page,'收藏地点')
        await page.getByRole('button',{name:'地图定位'}).waitFor()
        await click(page,'地图定位')
        await page.locator('.context h2').waitFor()
        await click(page,'退出')
        await page.getByRole('button',{name:'登录 / 注册'}).waitFor()
        console.log('Temporary account signup, favorite persistence, personal space, map locate, logout')
      }
      await page.close()
    }
    assert.deepEqual(problems,[])
    console.log('Paper UI checks passed')
  } finally {
    await browser.close()
  }
}

main().catch(e=>{console.error(e);process.exitCode=1})
